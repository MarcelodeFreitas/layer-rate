function calculateBasePrice(productionCostAllJobs, pricing) {
	if (pricing.mode === "markup") return productionCostAllJobs * (1 + percent(pricing.percent));
	return productionCostAllJobs / (1 - percent(pricing.percent));
}
function calculateFees(fees, baseCustomerPriceAllJobs) {
	return {
		recoverable: calculateRecoverableFees(fees, baseCustomerPriceAllJobs),
		addOnTop: []
	};
}
function calculateRecoverableFees(fees, baseCustomerPriceAllJobs) {
	const recoverableFees = fees.filter((fee) => fee.behavior === "recover");
	const totalFixedAmount = recoverableFees.reduce((sum, fee) => sum + (fee.fixedAmount ?? 0), 0);
	const totalPercent = recoverableFees.reduce((sum, fee) => sum + percent(fee.percent ?? 0), 0);
	const salePriceAllJobs = totalPercent === 0 ? baseCustomerPriceAllJobs + totalFixedAmount : (baseCustomerPriceAllJobs + totalFixedAmount) / (1 - totalPercent);
	return recoverableFees.map((fee) => toFeeBreakdown(fee, salePriceAllJobs));
}
function calculateAddOnTopFees(fees, basisAmount) {
	return fees.filter((fee) => fee.behavior === "addOnTop").map((fee) => toFeeBreakdown(fee, basisAmount));
}
function calculateCustomerCharge(fees, salePriceAllJobs, taxPercent, pricingOptions) {
	const addOnTopFees = fees.filter((fee) => fee.behavior === "addOnTop");
	const totalFixedAmount = addOnTopFees.reduce((sum, fee) => sum + (fee.fixedAmount ?? 0), 0);
	const totalPercent = addOnTopFees.reduce((sum, fee) => sum + percent(fee.percent ?? 0), 0);
	const taxIncludesAddOnTopFees = pricingOptions.taxBasis === "salePricePlusAddOnTopFees";
	const addOnPercentUsesFinalCustomerPrice = pricingOptions.addOnTopFeePercentBasis === "finalCustomerPrice";
	let addOnTopFeeBasis;
	if (addOnPercentUsesFinalCustomerPrice) {
		const taxFactor = taxIncludesAddOnTopFees ? 1 + taxPercent : 1;
		const denominator = 1 - totalPercent * taxFactor;
		if (denominator <= 0) throw new LayerRateCalculationError("addOnTop fee percentages are too high for final customer price basis.", { denominator });
		const addOnTopFeeAmount = (totalFixedAmount + totalPercent * salePriceAllJobs * taxFactor) / denominator;
		const tax = (taxIncludesAddOnTopFees ? salePriceAllJobs + addOnTopFeeAmount : salePriceAllJobs) * taxPercent;
		addOnTopFeeBasis = salePriceAllJobs + addOnTopFeeAmount + tax;
	} else {
		const denominator = 1 - totalPercent;
		addOnTopFeeBasis = salePriceAllJobs + (totalPercent === 0 ? totalFixedAmount : (totalFixedAmount + totalPercent * salePriceAllJobs) / denominator);
	}
	const addOnTopFeeBreakdown = calculateAddOnTopFees(fees, addOnTopFeeBasis);
	const addOnTopFeeAmount = sumFees(addOnTopFeeBreakdown);
	return {
		addOnTopFeeBreakdown,
		addOnTopFees: addOnTopFeeAmount,
		tax: (taxIncludesAddOnTopFees ? salePriceAllJobs + addOnTopFeeAmount : salePriceAllJobs) * taxPercent
	};
}
function toFeeBreakdown(fee, basisAmount) {
	const fixedAmount = fee.fixedAmount ?? 0;
	const feePercent = fee.percent ?? 0;
	return {
		name: fee.name,
		behavior: fee.behavior,
		fixedAmount,
		percent: feePercent,
		amount: fixedAmount + basisAmount * percent(feePercent)
	};
}
