const MAX_MARKUP_PERCENT = 1e6;
const BISECTION_STEPS = 200;
function solvePricingForPerJobPrice(input, perJobPrice) {
	if (!Number.isFinite(perJobPrice) || perJobPrice <= 0) throw new LayerRateCalculationError("Target price must be a positive number.", { perJobPrice });
	const quoteAt = (markupPercent) => calculateQuote({
		...input,
		pricing: {
			mode: "markup",
			percent: markupPercent
		}
	});
	const minimumPrice = quoteAt(0).perJobCustomerPrice;
	if (perJobPrice < minimumPrice) throw new LayerRateCalculationError("Target price is below the production cost, so no markup reaches it.", {
		perJobPrice,
		minimumPrice
	});
	if (quoteAt(MAX_MARKUP_PERCENT).perJobCustomerPrice < perJobPrice) throw new LayerRateCalculationError("Target price is too high to solve.", { perJobPrice });
	let low = 0;
	let high = MAX_MARKUP_PERCENT;
	for (let step = 0; step < BISECTION_STEPS; step += 1) {
		const middle = (low + high) / 2;
		if (quoteAt(middle).perJobCustomerPrice < perJobPrice) low = middle;
		else high = middle;
	}
	const result = quoteAt(high);
	const sellerReceives = result.sellerReceivesAllJobs;
	return {
		markupPercent: high,
		marginPercent: sellerReceives > 0 ? result.totalProfitAllJobs / sellerReceives * 100 : 0,
		result
	};
}
