	const operationsCostPerJob = operationsHours * input.laborCostPerHour;
	const postProcessingCostPerJob = postProcessingHours * input.laborCostPerHour;
	const failedJobSurchargePerJob = percent(input.failRatioPercent) * (materialCostPerJob + printerPowerCostPerJob + runtimeCostPerJob + operationsCostPerJob);
