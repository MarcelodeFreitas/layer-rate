async function readQuoteInput(filePath, useStdin) {
	if (useStdin && filePath !== void 0) throw new Error("Use either a file path or --stdin, not both.");
	if (useStdin) return parseQuoteJson(await readStdin(), "stdin");
	if (filePath === void 0) throw new Error("A quote input file is required unless --stdin is used.");
	let contents;
	try {
		contents = await readFile(filePath, "utf8");
	} catch (error) {
		throw new Error(`Could not read input file "${filePath}": ${messageFrom(error)}`);
	}
	return parseQuoteJson(contents, filePath);
}
async function writeJsonFile(filePath, value, force) {
	try {
		await writeFile(filePath, `${JSON.stringify(value, null, 2)}\n`, {
			encoding: "utf8",
			flag: force ? "w" : "wx"
		});
	} catch (error) {
		if (isFileExistsError(error) && !force) throw new Error(`File already exists: ${filePath}. Use --force to overwrite it.`);
		throw error;
	}
}
function messageFrom(error) {
	if (error instanceof Error) return error.message;
	return String(error);
}
async function readStdin() {
	const chunks = [];
	for await (const chunk of process.stdin) chunks.push(Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk));
	return Buffer.concat(chunks).toString("utf8");
}
function parseQuoteJson(contents, source) {
	let value;
	try {
		value = JSON.parse(stripBom(contents));
	} catch (error) {
		throw new Error(`Malformed JSON in ${source}: ${messageFrom(error)}`);
	}
	return parseQuoteInput(value);
}
function stripBom(contents) {
	return contents.charCodeAt(0) === 65279 ? contents.slice(1) : contents;
}
function isFileExistsError(error) {
	return typeof error === "object" && error !== null && "code" in error && error.code === "EEXIST";
}
